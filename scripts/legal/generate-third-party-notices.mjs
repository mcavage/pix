#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from the hand-maintained ledger in
// scripts/legal/dependencies.json, and (when a live module list is supplied)
// validates it against scripts/legal/notices-policy.json's fail-closed
// license-class gate (AC-REL-01).
//
// Pure rendering/validation logic is exported so tests can exercise it
// against fixtures without touching the real repo tree or shelling to `go`.
//
// CLI:
//   node generate-third-party-notices.mjs                 -> print to stdout
//   node generate-third-party-notices.mjs --write <path>   -> write to <path>
//   node generate-third-party-notices.mjs --check-live <live-modules-file> \
//       [--write <path>]
//     <live-modules-file>: newline-separated `module@version` (the output of
//     list-go-modules.sh). Exits non-zero and prints every offending module if
//     the live set diverges from the ledger (missing entry, or disallowed
//     license class) — this is the fail-closed gate itself.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HEADER = `# Third-Party Notices

This file is GENERATED by \`scripts/legal/generate-third-party-notices.mjs\`
from \`scripts/legal/dependencies.json\` (a hand-maintained ledger, re-derived
and diffed against the live dependency set by
\`scripts/check-third-party-notices.sh\` on every CI run — see
\`docs/legal/RELEASE-SAFEGUARDS.md\`). Do not hand-edit this file; edit the
ledger and regenerate.

pix is an independent project. It is not affiliated with, endorsed by, or
sponsored by any of the organizations named below; their names appear solely
to attribute the open-source components pix depends on. See \`NOTICE.md\`.
`;

export function splitModule(entry) {
	const at = entry.lastIndexOf("@");
	return { module: entry.slice(0, at), version: entry.slice(at + 1) };
}

export function classify(entry, policy) {
	if (!entry) return { ok: false, reason: "not present in dependencies.json ledger" };
	const cls = entry.class;
	if (!policy.allowedClasses.includes(cls)) {
		return { ok: false, reason: `license class "${cls}" is not in allowedClasses` };
	}
	if (cls === "weak-copyleft" && !policy.weakCopyleftAllowlist.includes(entry.module)) {
		return { ok: false, reason: `weak-copyleft not allowlisted for ${entry.module}` };
	}
	return { ok: true };
}

// Validate the ledger's `bakedTools` entries (ruff/fd/go — static binaries
// fetched directly by `curl` in the Dockerfile, pinned by an ARG, not managed
// by npm/go.mod) against the ACTUAL Dockerfile ARG pins. Fails closed on any
// drift (ledger says one version, Dockerfile pins another) or a tool present
// in one but not the other, so a bump to RUFF_VERSION/FD_VERSION/GO_VERSION
// that forgets the ledger doesn't silently go unnoticed.
// Returns { ok, findings[] }. findings[] entries: { tool, reason }.
export function validateBakedTools(dockerfileText, bakedTools) {
	const findings = [];
	for (const tool of bakedTools || []) {
		const argName = tool.dockerfileArg;
		if (!argName) {
			findings.push({ tool: tool.name, reason: "ledger entry has no dockerfileArg to cross-check" });
			continue;
		}
		const m = dockerfileText.match(new RegExp(`ARG ${argName}=(\\S+)`));
		if (!m) {
			findings.push({ tool: tool.name, reason: `Dockerfile has no "ARG ${argName}=..." (tool no longer baked, or ARG renamed — update the ledger)` });
			continue;
		}
		const live = m[1];
		if (live !== tool.version) {
			findings.push({
				tool: tool.name,
				reason: `ledger pins ${tool.version}, Dockerfile ARG ${argName} pins ${live} — re-verify the license at the new version and update the ledger`,
			});
		}
	}
	return { ok: findings.length === 0, findings };
}

// Validate a LIVE `module@version` list against the ledger + policy.
// Returns { ok, findings[] }. findings[] entries: { module, version, reason }.
export function validateLiveModules(liveEntries, deps, policy) {
	const byModule = new Map(deps.goModules.map((e) => [e.module, e]));
	const findings = [];
	for (const raw of liveEntries) {
		const trimmed = raw.trim();
		if (!trimmed) continue;
		const { module, version } = splitModule(trimmed);
		const entry = byModule.get(module);
		const verdict = classify(entry, policy);
		if (!verdict.ok) {
			findings.push({ module, version, reason: verdict.reason });
			continue;
		}
		if (entry.version !== version) {
			findings.push({
				module,
				version,
				reason: `ledger pins ${entry.version}, live build uses ${version} — re-verify the license at the new version and update the ledger`,
			});
		}
	}
	return { ok: findings.length === 0, findings };
}

function renderTable(rows, columns) {
	const header = `| ${columns.map((c) => c.label).join(" | ")} |`;
	const sep = `| ${columns.map(() => "---").join(" | ")} |`;
	const body = rows
		.map((r) => `| ${columns.map((c) => c.get(r)).join(" | ")} |`)
		.join("\n");
	return [header, sep, body].join("\n");
}

export function renderNotices(deps) {
	const goRows = [...deps.goModules].sort((a, b) => a.module.localeCompare(b.module));
	const npmRows = [...deps.npmGlobal].sort((a, b) => a.name.localeCompare(b.name));
	const plannedRows = deps.goModulesPlanned || [];
	const bakedToolRows = [...(deps.bakedTools || [])].sort((a, b) => a.name.localeCompare(b.name));

	const parts = [HEADER];

	if (bakedToolRows.length) {
		parts.push("## Directly-downloaded/baked toolchain binaries (Dockerfile)\n");
		parts.push(
			"These are NOT npm/go-module dependencies — they are static binaries or\ntarballs fetched directly by `curl` in the Dockerfile from the project's own\nGitHub Releases (or, for Go, go.dev/dl), pinned by an explicit `ARG` (never\n`releases/latest`) so builds stay reproducible and the pin is one grep away\nfrom the source of truth.\n"
		);
		parts.push(
			renderTable(bakedToolRows, [
				{ label: "Tool", get: (r) => r.name },
				{ label: "Version", get: (r) => r.version },
				{ label: "License", get: (r) => r.license },
				{ label: "Source", get: (r) => r.source },
			])
		);
		parts.push("");
		for (const r of bakedToolRows) {
			parts.push(`- **${r.name}@${r.version}** (${r.license}) — ${r.role}`);
		}
		parts.push("");
	}

	parts.push("## Go modules (services/host — pix-host)\n");
	parts.push(
		renderTable(goRows, [
			{ label: "Module", get: (r) => r.module },
			{ label: "Version", get: (r) => r.version },
			{ label: "License", get: (r) => r.license },
		])
	);
	parts.push("");
	const mpl = goRows.filter((r) => r.class === "weak-copyleft");
	if (mpl.length) {
		parts.push(
			"### MPL-2.0 components (weak copyleft — noted per MPL-2.0 s3.3)\n"
		);
		for (const r of mpl) {
			parts.push(`- **${r.module}@${r.version}** — MPL-2.0. ${r.notes || ""}`.trim());
		}
		parts.push("");
	}

	if (plannedRows.length) {
		parts.push("## Planned Go modules (not yet vendored)\n");
		parts.push(
			"These are named here ahead of adoption so the license posture is on record before the dependency lands, not after."
		);
		parts.push("");
		for (const r of plannedRows) {
			parts.push(
				`- **${r.module}** — status: planned. License: ${r.license} (${r.licenseEvidence}). ${r.caveat}`
			);
		}
		parts.push("");
	}

	parts.push("## npm packages baked into the image (Dockerfile `npm install -g` / `pi install`)\n");
	parts.push(
		renderTable(npmRows, [
			{ label: "Package", get: (r) => r.name },
			{ label: "Version", get: (r) => r.version },
			{ label: "License", get: (r) => r.license },
		])
	);
	parts.push("");
	const patched = npmRows.filter((r) => /PATCH/i.test(r.role || ""));
	if (patched.length) {
		parts.push("### Patched at build time\n");
		for (const r of patched) {
			parts.push(`- **${r.name}@${r.version}** (${r.license}) — ${r.role}`);
		}
		parts.push("");
	}

	parts.push(
		"---\n\nFull upstream license texts are not reproduced verbatim here (each is available from its module cache / npm package under the versions pinned above and in `go.sum` / the Dockerfile); this file exists to enumerate what is bundled and under what terms, per the fail-closed gate in `scripts/check-third-party-notices.sh`.\n"
	);

	return parts.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

function main() {
	const args = process.argv.slice(2);
	const here = dirname(fileURLToPath(import.meta.url));
	const deps = JSON.parse(readFileSync(join(here, "dependencies.json"), "utf8"));
	const policy = JSON.parse(readFileSync(join(here, "notices-policy.json"), "utf8"));

	const liveIdx = args.indexOf("--check-live");
	if (liveIdx !== -1) {
		const liveFile = args[liveIdx + 1];
		if (!liveFile) {
			console.error("--check-live requires a file path");
			process.exit(2);
		}
		const liveEntries = readFileSync(liveFile, "utf8").split("\n");
		const { ok, findings } = validateLiveModules(liveEntries, deps, policy);
		if (!ok) {
			console.error("license-class gate FAILED (fail-closed, AC-REL-01):");
			for (const f of findings) {
				console.error(`  - ${f.module}@${f.version}: ${f.reason}`);
			}
			process.exit(1);
		}
		console.error(`license-class gate OK (${liveEntries.filter((l) => l.trim()).length} live modules)`);
	}

	const dockerfileIdx = args.indexOf("--check-baked-tools");
	if (dockerfileIdx !== -1) {
		const dockerfilePath = args[dockerfileIdx + 1];
		if (!dockerfilePath) {
			console.error("--check-baked-tools requires a Dockerfile path");
			process.exit(2);
		}
		const dockerfileText = readFileSync(dockerfilePath, "utf8");
		const { ok, findings } = validateBakedTools(dockerfileText, deps.bakedTools);
		if (!ok) {
			console.error("baked-tool version gate FAILED (fail-closed):");
			for (const f of findings) {
				console.error(`  - ${f.tool}: ${f.reason}`);
			}
			process.exit(1);
		}
		console.error(`baked-tool version gate OK (${(deps.bakedTools || []).length} tools)`);
	}

	const rendered = renderNotices(deps);
	const writeIdx = args.indexOf("--write");
	if (writeIdx !== -1) {
		const outPath = args[writeIdx + 1];
		if (!outPath) {
			console.error("--write requires a file path");
			process.exit(2);
		}
		writeFileSync(outPath, rendered);
	} else {
		process.stdout.write(rendered);
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	main();
}
